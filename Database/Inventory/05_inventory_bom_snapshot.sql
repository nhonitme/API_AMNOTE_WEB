-- AMnote IO material allocation snapshot. Run in each COMPANY database (MySQL 5.6+).
-- Deliberately no UNIT_ID: display unit is joined from product_info.
-- A snapshot is written in the same transaction as chit_inventory_output.
-- Stored procedures: 07_sp_inventory_bom.sql
CREATE TABLE IF NOT EXISTS chit_inventory_bom_finished (
  FINISHED_LINE_ID BIGINT NOT NULL AUTO_INCREMENT,
  COMPANY_CD VARCHAR(20) COLLATE utf8_unicode_ci NOT NULL DEFAULT '',
  INVENTORY_ID BIGINT NOT NULL,
  FINISHED_PRODUCT_ID BIGINT NOT NULL,
  FINISHED_QUANTITY DECIMAL(24,6) NOT NULL DEFAULT 0,
  SORT INT NOT NULL DEFAULT 0,
  ISDEL CHAR(1) COLLATE utf8_unicode_ci NOT NULL DEFAULT '0' COMMENT '1: đã xoá',
  CREATE_BY VARCHAR(20) COLLATE utf8_unicode_ci NOT NULL DEFAULT '' COMMENT 'Người tạo',
  CREATE_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo',
  UPDATE_BY VARCHAR(20) COLLATE utf8_unicode_ci NOT NULL DEFAULT '' COMMENT 'Người cập nhật',
  UPDATE_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật',
  PRIMARY KEY (FINISHED_LINE_ID),
  KEY IDX_BOM_FINISHED_VOUCHER (COMPANY_CD, INVENTORY_ID, ISDEL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci;

CREATE TABLE IF NOT EXISTS chit_inventory_bom_material (
  BOM_MATERIAL_ID BIGINT NOT NULL AUTO_INCREMENT,
  COMPANY_CD VARCHAR(20) COLLATE utf8_unicode_ci NOT NULL DEFAULT '',
  INVENTORY_ID BIGINT NOT NULL,
  FINISHED_LINE_ID BIGINT NOT NULL,
  MATERIAL_PRODUCT_ID BIGINT NOT NULL,
  STORE_ID BIGINT DEFAULT NULL,
  BOM_QUANTITY DECIMAL(24,10) NOT NULL DEFAULT 0,
  CALCULATED_QUANTITY DECIMAL(24,6) NOT NULL DEFAULT 0,
  CONFIRMED_QUANTITY DECIMAL(24,6) NOT NULL DEFAULT 0,
  OUTPUT_ID BIGINT DEFAULT NULL,
  SORT INT NOT NULL DEFAULT 0,
  ISDEL CHAR(1) COLLATE utf8_unicode_ci NOT NULL DEFAULT '0' COMMENT '1: đã xoá',
  CREATE_BY VARCHAR(20) COLLATE utf8_unicode_ci NOT NULL DEFAULT '' COMMENT 'Người tạo',
  CREATE_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo',
  UPDATE_BY VARCHAR(20) COLLATE utf8_unicode_ci NOT NULL DEFAULT '' COMMENT 'Người cập nhật',
  UPDATE_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật',
  PRIMARY KEY (BOM_MATERIAL_ID),
  KEY IDX_BOM_MATERIAL_VOUCHER (COMPANY_CD, INVENTORY_ID, ISDEL),
  KEY IDX_BOM_MATERIAL_FINISHED (FINISHED_LINE_ID),
  KEY IDX_BOM_MATERIAL_OUTPUT (COMPANY_CD, OUTPUT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci;
